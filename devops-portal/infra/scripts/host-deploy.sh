#!/bin/bash
# Deploys (or redeploys) the DevOps portal on the portal host.
#
# Runs ON the EC2 host:
#   - at first boot, from user_data
#   - on every release, via `aws ssm send-command` from portal-release.yml
#
# Usage: host-deploy.sh <git-ref-or-sha> [--wait-for-secrets]
#
# Steps: fetch the repo at <ref> -> render devops-portal/.env from SSM
# Parameter Store -> docker compose up --build. Secrets are only ever written
# to the .env file (mode 600, root-owned) - never to the repo or the logs.
set -euo pipefail

REF="${1:-main}"
WAIT_FOR_SECRETS="${2:-}"

# shellcheck disable=SC1091
source /opt/devops-portal/host.env   # AWS_REGION, SSM_PREFIX, GITHUB_REPO
SRC=/opt/devops-portal/src
APP="$SRC/devops-portal"

param() {
  aws ssm get-parameter --region "$AWS_REGION" --with-decryption \
    --name "$SSM_PREFIX/$1" --query Parameter.Value --output text 2>/dev/null
}

# The secrets are written by bootstrap-secrets.sh, which an operator may run
# after the instance has booted - so the first boot waits for them.
if [ "$WAIT_FOR_SECRETS" = "--wait-for-secrets" ]; then
  for _ in $(seq 1 120); do
    param encryption_key >/dev/null && break
    echo "Waiting for $SSM_PREFIX/encryption_key in SSM..."
    sleep 15
  done
fi
for required in encryption_key jwt_secret workflow_key github_token; do
  if ! param "$required" >/dev/null; then
    echo "Missing $SSM_PREFIX/$required - run infra/scripts/bootstrap-secrets.sh," >&2
    echo "then re-run: /opt/devops-portal/bin/host-deploy.sh $REF" >&2
    exit 1
  fi
done

echo "==> Fetching $GITHUB_REPO @ $REF"
if [ ! -d "$SRC/.git" ]; then
  git clone --quiet "https://github.com/$GITHUB_REPO.git" "$SRC"
fi
git -C "$SRC" fetch --quiet --prune origin "+refs/heads/*:refs/remotes/origin/*"
if git -C "$SRC" rev-parse --verify --quiet "origin/$REF" >/dev/null; then
  git -C "$SRC" checkout --quiet --force --detach "origin/$REF"
else
  git -C "$SRC" fetch --quiet origin "$REF"
  git -C "$SRC" checkout --quiet --force --detach "$REF"
fi
echo "==> At commit $(git -C "$SRC" rev-parse --short HEAD)"

# Keep this script itself up to date for the next release.
install -m 755 "$APP/infra/scripts/host-deploy.sh" /opt/devops-portal/bin/host-deploy.sh

echo "==> Rendering .env from SSM ($SSM_PREFIX/*)"
PUBLIC_HOST="$(param public_host)"
umask 077
cat > "$APP/.env" <<EOF
# Generated by host-deploy.sh from SSM Parameter Store - do not edit by hand.
PORTAL_HTTP_PORT=80
PORTAL_PUBLIC_HOST=$PUBLIC_HOST
CORS_ORIGINS=https://$PUBLIC_HOST
PORTAL_COOKIE_SECURE=true
PORTAL_ALLOW_SIGNUP=$(param allow_signup || echo true)
AWS_DEFAULT_REGION=$AWS_REGION

PORTAL_ENCRYPTION_KEY=$(param encryption_key)
PORTAL_JWT_SECRET=$(param jwt_secret)
PORTAL_WORKFLOW_KEY=$(param workflow_key)
GRAFANA_ADMIN_PASSWORD=$(param grafana_admin_password)

# github_actions needs portal-deploy.yml on the repo's default branch
# (a GitHub rule for workflow_dispatch); until then use local.
DEPLOYMENT_RUNNER_MODE=$(param runner_mode || echo github_actions)
GITHUB_REPO=$(param github_repo)
GITHUB_TOKEN=$(param github_token)
GITHUB_WORKFLOW=portal-deploy.yml
GITHUB_REF_NAME=$(param github_ref || echo main)

# The host runs in the default VPC: scrape node_exporter on private IPs so
# the SG-to-SG rule on deployed instances applies.
PROMETHEUS_SCRAPE_ADDRESS=private
PORTAL_MONITORING_SG_ID=$(param monitoring_sg_id)
PORTAL_MONITORING_SG_REGION=$(param monitoring_sg_region)
EOF
umask 022

echo "==> docker compose up"
cd "$APP"
docker compose up -d --build --remove-orphans
docker image prune -f >/dev/null

echo "==> Waiting for the backend health check"
for _ in $(seq 1 30); do
  if curl -fsS http://127.0.0.1/api/health >/dev/null; then
    echo "==> Portal is healthy"
    docker compose ps
    exit 0
  fi
  sleep 5
done
echo "Backend did not become healthy in time" >&2
docker compose ps
docker compose logs --tail 50 backend >&2
exit 1
