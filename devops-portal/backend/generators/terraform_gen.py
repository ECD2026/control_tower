"""
Dynamically generates Terraform HCL configuration based on user input.

Naming convention (so portal resources are easy to tell apart in the console):
  security group : devops-portal-<deployment8>-sg-<random>
  key pair       : devops-portal-<deployment8>-<key name>-<random>
  instances      : <name or devops-portal-<deployment8>>-<n>
Every resource carries Project=devops-portal, ManagedBy=DevOpsAutomationPortal
and PortalDeploymentId=<full id>; the portal uses the last tag to find the
instances a GitHub Actions run created.
"""

